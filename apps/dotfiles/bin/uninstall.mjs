const LEGACY_MARKER = '<!-- generated by ab-dotfiles -->'

function removeManaged(dir, names) {
  let removed = 0
  for (const name of names) {
    const filePath = path.join(dir, `${name}.md`)
    if (fs.existsSync(filePath)) {
      fs.unlinkSync(filePath)
      removed++
    }
  }
  return removed
}

/** 找出 ~/.claude/skills/ 下所有 ab-tao 管理的 skill 目錄 */
function findManagedSkillDirs(skillsDir) {
  const managed = []
  if (!fs.existsSync(skillsDir))
    return managed

  function walk(dir, depth) {
    if (depth > 3)
      return
    let entries
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true })
    }
    catch {
      return
    }
    for (const entry of entries) {
      if (!entry.isDirectory() || entry.isSymbolicLink())
        continue
      const fullPath = path.join(dir, entry.name)
      const skillFile = path.join(fullPath, 'SKILL.md')
      const skillFileDisabled = path.join(fullPath, 'SKILL.md.disabled')
      const markerFile = fs.existsSync(skillFile)
        ? skillFile
        : fs.existsSync(skillFileDisabled)
          ? skillFileDisabled
          : null
      if (markerFile) {
        try {
          const head = fs.readFileSync(markerFile, 'utf8').slice(0, 100)
          if (
            /^<!-- generated by ab-tao(?:::\S+)? -->/.test(head)
            || head.startsWith(LEGACY_MARKER)
          ) {
            managed.push(fullPath)
          }
        }
        catch {
          /* 跳過無法讀取的 */
        }
      }
      else {
        walk(fullPath, depth + 1)
      }
    }
  }
  walk(skillsDir, 0)
  return managed
}

async function main() {
  p.intro(' ab-tao 卸載 ')

  // 統計將刪除的項目
  const skillDirs = findManagedSkillDirs(path.join(CLAUDE_DIR, 'skills'))
  const stats = {
    commands: ALL_COMMANDS.filter(c =>
      fs.existsSync(path.join(CLAUDE_DIR, 'commands', `${c}.md`)),
    ).length,
    agents: ALL_AGENTS.filter(a =>
      fs.existsSync(path.join(CLAUDE_DIR, 'agents', `${a}.md`)),
    ).length,
    rules: ALL_RULES.filter(r =>
      fs.existsSync(path.join(CLAUDE_DIR, 'rules', `${r}.md`)),
    ).length,
    skills: skillDirs.length,
    // Bug 1 修復：改為統計 settings.json 中 id 以 ab-tao: 開頭的 hook 條目數量
    hooks: (() => {
      const settingsPath = path.join(CLAUDE_DIR, 'settings.json')
      if (!fs.existsSync(settingsPath))
        return 0
      try {
        const data = JSON.parse(fs.readFileSync(settingsPath, 'utf8'))
        if (!data.hooks || typeof data.hooks !== 'object')
          return 0
        return Object.values(data.hooks)
          .flat()
          .filter(
            e => typeof e?.id === 'string' && e.id.startsWith('ab-tao:'),
          )
          .length
      }
      catch {
        return 0
      }
    })(),
    settings: fs.existsSync(path.join(CLAUDE_DIR, 'settings.json')) ? 1 : 0,
    keybindings: fs.existsSync(path.join(CLAUDE_DIR, 'keybindings.json'))
      ? 1
      : 0,
    // Bug 2 修復：加入 relocate-plan.sh，與刪除清單對齊
    hookScripts: (() => {
      const hooksDir = path.join(CLAUDE_DIR, 'hooks')
      if (!fs.existsSync(hooksDir))
        return 0
      return fs
        .readdirSync(hooksDir)
        .filter(f =>
          [
            'hook-handler.sh',
            'protect-files.sh',
            'block-dangerous.sh',
            'validate-memory-path.sh',
            'inject-project-prompt.sh',
            'relocate-plan.sh',
          ].includes(f),
        )
        .length
    })(),
  }
  const total
    = stats.commands
      + stats.agents
      + stats.rules
      + stats.skills
      + stats.hooks
      + stats.settings
      + stats.keybindings
      + stats.hookScripts

  if (total === 0) {
    p.log.info('沒有找到 ab-tao 管理的配置')
    p.outro()
    return
  }

  p.log.info(`將移除：
    ${stats.commands} commands · ${stats.agents} agents · ${stats.rules} rules · ${stats.skills} skills
    ${stats.hooks ? `${stats.hooks} hooks · ` : ''}${stats.settings ? 'settings.json · ' : ''}${stats.keybindings ? 'keybindings.json · ' : ''}${stats.hookScripts ? `${stats.hookScripts} hook scripts` : ''}

用戶自訂的 commands/agents/rules/skills 不會被刪除。
完全恢復到 setup 前：pnpm run d:restore → 選擇「完全還原」`)

  const confirm = await p.confirm({
    message: '確定卸載？',
    initialValue: false,
  })
  if (!confirm || p.isCancel(confirm)) {
    p.outro('已取消')
    return
  }

  let removed = 0
  removed += removeManaged(path.join(CLAUDE_DIR, 'commands'), ALL_COMMANDS)
  removed += removeManaged(path.join(CLAUDE_DIR, 'agents'), ALL_AGENTS)
  removed += removeManaged(path.join(CLAUDE_DIR, 'rules'), ALL_RULES)

  for (const dir of skillDirs) {
    fs.rmSync(dir, { recursive: true, force: true })
    removed++
  }

  // Bug 1 修復：從 settings.json 的 hooks 欄位過濾 ab-tao: 條目，保留其他外掛（如 ECC）的 hooks
  const settingsJsonPath = path.join(CLAUDE_DIR, 'settings.json')
  if (fs.existsSync(settingsJsonPath)) {
    try {
      const settingsData = JSON.parse(
        fs.readFileSync(settingsJsonPath, 'utf8'),
      )
      let changed = false
      if (settingsData.hooks && typeof settingsData.hooks === 'object') {
        for (const [event, entries] of Object.entries(settingsData.hooks)) {
          if (!Array.isArray(entries))
            continue
          const filtered = entries.filter(
            e => typeof e.id !== 'string' || !e.id.startsWith('ab-tao:'),
          )
          if (filtered.length !== entries.length) {
            if (filtered.length === 0) {
              delete settingsData.hooks[event]
            }
            else {
              settingsData.hooks[event] = filtered
            }
            changed = true
          }
        }
        // 若 hooks 物件已空，移除整個 hooks 欄位
        if (changed && Object.keys(settingsData.hooks).length === 0) {
          delete settingsData.hooks
        }
      }
      if (changed) {
        const tmp = `${settingsJsonPath}.tmp.${process.pid}`
        fs.writeFileSync(
          tmp,
          `${JSON.stringify(settingsData, null, 2)}\n`,
          'utf8',
        )
        fs.renameSync(tmp, settingsJsonPath)
        removed++
      }
    }
    catch {
      /* settings.json 無法解析，跳過 */
    }
  }

  for (const file of ['keybindings.json']) {
    const fp = path.join(CLAUDE_DIR, file)
    if (fs.existsSync(fp)) {
      fs.unlinkSync(fp)
      removed++
    }
  }

  // hook 輔助設定檔
  for (const f of [
    '.prefs',
    '.protected-files',
    '.dangerous-patterns',
    '.notify-queue',
    '.notify-queue.time',
  ]) {
    const fp = path.join(CLAUDE_DIR, 'hooks', f)
    if (fs.existsSync(fp)) {
      fs.unlinkSync(fp)
      removed++
    }
  }

  for (const sh of [
    'hook-handler.sh',
    'protect-files.sh',
    'block-dangerous.sh',
    'validate-memory-path.sh',
    'inject-project-prompt.sh',
    'relocate-plan.sh',
  ]) {
    const shPath = path.join(CLAUDE_DIR, 'hooks', sh)
    if (fs.existsSync(shPath)) {
      fs.unlinkSync(shPath)
      removed++
    }
  }

  p.log.success(`已移除 ${removed} 個檔案`)

  p.outro('卸載完成')
}

/**
 * 移除單一 feature 的所有管理檔案
 * 使用方式：node uninstall.mjs --feature <featureName>
 */
function removeFeature(featureName) {
  const feature = FEATURE_REGISTRY.find(f => f.name === featureName)
  if (!feature) {
    console.error(
      `未知 feature: ${featureName}。可用：${FEATURE_REGISTRY.map(f => f.name).join(', ')}`,
    )
    process.exit(1)
  }
  let removed = 0
  for (const relFile of feature.files) {
    const fullPath = path.join(
      HOME,
      relFile.replace(/^\.claude\//, '.claude/'),
    )
    if (fs.existsSync(fullPath)) {
      fs.unlinkSync(fullPath)
      removed++
      console.log(`  已移除 ${relFile}`)
    }
  }
  console.log(`✅ feature "${featureName}" 移除完成（${removed} 個檔案）`)
}

// --feature 單獨 feature 移除（非互動式，直接執行）
if (process.argv.includes('--feature')) {
  const idx = process.argv.indexOf('--feature')
  const featureName = process.argv[idx + 1]
  if (featureName) {
    removeFeature(featureName)
    process.exit(0)
  }
}

main().catch((e) => {
  console.error(e.message)
  process.exit(1)
})
