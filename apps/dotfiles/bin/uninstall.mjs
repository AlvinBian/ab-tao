#!/usr/bin/env node

/**
 * 移除 ab-tao 安裝的所有配置
 *
 * 只刪除 ab-tao 管理的項目，保留用戶自訂的。
 * 使用 pnpm run restore 可選擇恢復到首次 setup 前的狀態。
 */

import fs from "node:fs";
import path from "node:path";
import * as p from "@clack/prompts";
import {
	ALL_AGENTS,
	ALL_COMMANDS,
	ALL_RULES,
} from "../libs/config/config-classifier.mjs";
import { HOME } from "../libs/core/paths.mjs";

const CLAUDE_DIR = path.join(HOME, ".claude");
const LEGACY_MARKER = "<!-- generated by ab-dotfiles -->";

function removeManaged(dir, names) {
	let removed = 0;
	for (const name of names) {
		const filePath = path.join(dir, `${name}.md`);
		if (fs.existsSync(filePath)) {
			fs.unlinkSync(filePath);
			removed++;
		}
	}
	return removed;
}

/** 找出 ~/.claude/skills/ 下所有 ab-tao 管理的 skill 目錄 */
function findManagedSkillDirs(skillsDir) {
	const managed = [];
	if (!fs.existsSync(skillsDir)) return managed;

	function walk(dir, depth) {
		if (depth > 3) return;
		let entries;
		try {
			entries = fs.readdirSync(dir, { withFileTypes: true });
		} catch {
			return;
		}
		for (const entry of entries) {
			if (!entry.isDirectory() || entry.isSymbolicLink()) continue;
			const fullPath = path.join(dir, entry.name);
			const skillFile = path.join(fullPath, "SKILL.md");
			const skillFileDisabled = path.join(fullPath, "SKILL.md.disabled");
			const markerFile = fs.existsSync(skillFile)
				? skillFile
				: fs.existsSync(skillFileDisabled)
					? skillFileDisabled
					: null;
			if (markerFile) {
				try {
					const head = fs.readFileSync(markerFile, "utf8").slice(0, 100);
					if (
						/^<!-- generated by ab-tao(?:::\S+)? -->/.test(head) ||
						head.startsWith(LEGACY_MARKER)
					) {
						managed.push(fullPath);
					}
				} catch {
					/* 跳過無法讀取的 */
				}
			} else {
				walk(fullPath, depth + 1);
			}
		}
	}
	walk(skillsDir, 0);
	return managed;
}

async function main() {
	p.intro(" ab-tao 卸載 ");

	// 統計將刪除的項目
	const skillDirs = findManagedSkillDirs(path.join(CLAUDE_DIR, "skills"));
	const stats = {
		commands: ALL_COMMANDS.filter((c) =>
			fs.existsSync(path.join(CLAUDE_DIR, "commands", `${c}.md`)),
		).length,
		agents: ALL_AGENTS.filter((a) =>
			fs.existsSync(path.join(CLAUDE_DIR, "agents", `${a}.md`)),
		).length,
		rules: ALL_RULES.filter((r) =>
			fs.existsSync(path.join(CLAUDE_DIR, "rules", `${r}.md`)),
		).length,
		skills: skillDirs.length,
		hooks: fs.existsSync(path.join(CLAUDE_DIR, "hooks.json")) ? 1 : 0,
		settings: fs.existsSync(path.join(CLAUDE_DIR, "settings.json")) ? 1 : 0,
		keybindings: fs.existsSync(path.join(CLAUDE_DIR, "keybindings.json"))
			? 1
			: 0,
		hookScripts: (() => {
			const hooksDir = path.join(CLAUDE_DIR, "hooks");
			if (!fs.existsSync(hooksDir)) return 0;
			return fs
				.readdirSync(hooksDir)
				.filter((f) =>
					[
						"hook-handler.sh",
						"protect-files.sh",
						"block-dangerous.sh",
						"validate-memory-path.sh",
						"inject-project-prompt.sh",
					].includes(f),
				).length;
		})(),
	};
	const total =
		stats.commands +
		stats.agents +
		stats.rules +
		stats.skills +
		stats.hooks +
		stats.settings +
		stats.keybindings +
		stats.hookScripts;

	if (total === 0) {
		p.log.info("沒有找到 ab-tao 管理的配置");
		p.outro();
		return;
	}

	p.log.info(`將移除：
	  ${stats.commands} commands · ${stats.agents} agents · ${stats.rules} rules · ${stats.skills} skills
	  ${stats.hooks ? "hooks.json · " : ""}${stats.settings ? "settings.json · " : ""}${stats.keybindings ? "keybindings.json · " : ""}${stats.hookScripts ? `${stats.hookScripts} hook scripts` : ""}

用戶自訂的 commands/agents/rules/skills 不會被刪除。
完全恢復到 setup 前：pnpm run restore → 選擇「完全還原」`);

	const confirm = await p.confirm({
		message: "確定卸載？",
		initialValue: false,
	});
	if (!confirm || p.isCancel(confirm)) {
		p.outro("已取消");
		return;
	}

	let removed = 0;
	removed += removeManaged(path.join(CLAUDE_DIR, "commands"), ALL_COMMANDS);
	removed += removeManaged(path.join(CLAUDE_DIR, "agents"), ALL_AGENTS);
	removed += removeManaged(path.join(CLAUDE_DIR, "rules"), ALL_RULES);

	for (const dir of skillDirs) {
		fs.rmSync(dir, { recursive: true, force: true });
		removed++;
	}

	// hooks.json：只移除 ab-tao: 條目，保留其他外掛（如 ECC）的 hooks
	const hooksJsonPath = path.join(CLAUDE_DIR, "hooks.json");
	if (fs.existsSync(hooksJsonPath)) {
		try {
			const hooksData = JSON.parse(fs.readFileSync(hooksJsonPath, "utf8"));
			let changed = false;
			if (hooksData.hooks && typeof hooksData.hooks === "object") {
				for (const [event, entries] of Object.entries(hooksData.hooks)) {
					if (!Array.isArray(entries)) continue;
					const filtered = entries.filter(
						(e) => typeof e.id !== "string" || !e.id.startsWith("ab-tao:"),
					);
					if (filtered.length !== entries.length) {
						hooksData.hooks[event] = filtered;
						changed = true;
					}
				}
			}
			if (changed) {
				const tmp = `${hooksJsonPath}.tmp.${process.pid}`;
				fs.writeFileSync(
					tmp,
					JSON.stringify(hooksData, null, 2) + "\n",
					"utf8",
				);
				fs.renameSync(tmp, hooksJsonPath);
				removed++;
			}
		} catch {
			/* hooks.json 無法解析，跳過 */
		}
	}

	for (const file of ["settings.json", "keybindings.json"]) {
		const fp = path.join(CLAUDE_DIR, file);
		if (fs.existsSync(fp)) {
			fs.unlinkSync(fp);
			removed++;
		}
	}

	// hook 輔助設定檔
	for (const f of [
		".prefs",
		".protected-files",
		".dangerous-patterns",
		".notify-queue",
		".notify-queue.time",
	]) {
		const fp = path.join(CLAUDE_DIR, "hooks", f);
		if (fs.existsSync(fp)) {
			fs.unlinkSync(fp);
			removed++;
		}
	}

	for (const sh of [
		"hook-handler.sh",
		"protect-files.sh",
		"block-dangerous.sh",
		"validate-memory-path.sh",
		"inject-project-prompt.sh",
	]) {
		const shPath = path.join(CLAUDE_DIR, "hooks", sh);
		if (fs.existsSync(shPath)) {
			fs.unlinkSync(shPath);
			removed++;
		}
	}

	p.log.success(`已移除 ${removed} 個檔案`);

	// 可選：清除 iCloud 同步
	try {
		const { getSyncStatus, clearSync } = await import(
			"../libs/external/ab-async.mjs"
		);
		const sync = getSyncStatus();
		if (sync.available && sync.lastPush) {
			const clearICloud = await p.confirm({
				message: "同時清除 iCloud 同步的偏好備份？",
				initialValue: false,
			});
			if (!p.isCancel(clearICloud) && clearICloud) {
				clearSync();
				p.log.success("iCloud 同步資料已清除");
			}
		}
	} catch {
		/* iCloud 模組不可用時跳過 */
	}

	p.outro("卸載完成");
}

main().catch((e) => {
	console.error(e.message);
	process.exit(1);
});
