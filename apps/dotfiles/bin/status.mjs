async function terminalMode(data) {
  // skills 在 collectFullStatus() 不回傳，統一在此掃描一次
  if (!data.skills)
    data.skills = scanSkillsDir()
  let currentData = data
  showOverview(currentData)

  while (true) {
    const action = await p.select({
      message: '要做什麼？',
      options: [
        { value: 'detail', label: '📋 查看詳情', hint: '展開某個分類' },
        { value: 'manage', label: '⚙️ 管理配置', hint: '增/刪/啟用/關閉' },
        {
          value: 'console',
          label: '🖥 開啟 Web Console',
          hint: '執行 pnpm run cs:open 啟動後台控制台',
        },
        { value: 'refresh', label: '🔄 重新掃描', hint: '更新使用數據' },
        { value: 'exit', label: '👋 退出' },
      ],
    })
    if (p.isCancel(action) || action === 'exit')
      break
    if (action === 'detail') {
      while (true) {
        const cont = await showDetail(currentData)
        if (!cont)
          break
      }
    }
    if (action === 'manage') {
      const changed = await manageConfig(currentData)
      if (changed) {
        const spinner = p.spinner()
        spinner.start('重新掃描…')
        try {
          currentData = await collectFullStatus()
        }
        finally {
          spinner.stop('已更新')
        }
        showOverview(currentData)
      }
    }
    if (action === 'console') {
      p.log.info('請執行 pnpm run cs:open 啟動 Web 後台控制台')
      p.log.info('或使用 pnpm run cs:dev 進入開發模式')
    }
    if (action === 'refresh') {
      const spinner = p.spinner()
      spinner.start('重新掃描…')
      try {
        currentData = await collectFullStatus()
      }
      finally {
        spinner.stop('已更新')
      }
      showOverview(currentData)
    }
  }
  p.outro(pc.dim('再見'))
}

