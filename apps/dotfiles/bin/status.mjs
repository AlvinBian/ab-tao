// 管理配置
// ═══════════════════════════════════════════════════════════════

async function manageConfig(data) {
  let changed = false
  const category = await p.select({
    message: '管理哪個分類？',
    options: [
      { value: 'commands', label: '⌨️ Commands — 刪除 / 從 ECC 新增' },
      { value: 'agents', label: '🤖 Agents — 刪除 / 從 ECC 新增' },
      { value: 'rules', label: '📐 Rules — 啟用 / 停用 / 刪除 / 從 ECC 新增' },
      { value: 'skills', label: '🎯 Skills — 啟用 / 停用 / 刪除' },
      { value: 'hooks', label: '🪝 Hooks — 移除事件' },
      { value: 'zsh', label: '🐚 ZSH — 安裝 / 卸載模組' },
      { value: 'permissions', label: '🔐 Permissions — 新增 / 刪除規則' },
      { value: 'claudemd', label: '📝 CLAUDE.md — 刪除' },
      { value: 'back', label: '← 返回' },
    ],
  })
  if (p.isCancel(category) || category === 'back')
    return false

  if (category === 'commands' || category === 'agents') {
    const items = category === 'commands' ? data.commands : data.agents
    const dir = path.join(CLAUDE_DIR, category)
    const aiResItems
      = category === 'commands' ? data.aiRes.commands : data.aiRes.agents
    const notInstalled = aiResItems.filter(
      name => !items.some(i => i.name === name),
    )

    const action = await p.select({
      message: `${category} 操作`,
      options: [
        {
          value: 'delete',
          label: '🗑️ 刪除已安裝的',
          hint: `${items.filter(i => i.count === 0).length} 個從未使用`,
        },
        ...(!isEmpty(notInstalled)
          ? [
              {
                value: 'add',
                label: '➕ 從 ECC 新增',
                hint: `${notInstalled.length} 個可新增`,
              },
            ]
          : []),
        { value: 'back', label: '← 返回' },
      ],
    })
    if (p.isCancel(action) || action === 'back')
      return false

    if (action === 'delete') {
      const selected = await p.multiselect({
        message: `選擇要刪除的 ${category}（空格選擇，Enter 確認）`,
        options: items.map(i => ({
          value: i.name,
          label: `${i.count > 0 ? '  ' : pc.red('✘ ')}${i.name}`,
          hint: i.count > 0 ? `${i.count}次` : '從未使用',
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        for (const name of selected) {
          const fp = path.join(dir, `${name}.md`)
          if (fs.existsSync(fp)) {
            fs.unlinkSync(fp)
            p.log.success(`已刪除 ${name}`)
            changed = true
          }
        }
      }
    }
    else if (action === 'add') {
      const selected = await p.multiselect({
        message: `選擇要新增的 ${category}`,
        options: notInstalled.map(name => ({ value: name, label: name })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        const aiResCategoryDir = path.join(ECC_DIR, category)
        for (const name of selected) {
          const src = path.join(aiResCategoryDir, `${name}.md`)
          const dest = path.join(dir, `${name}.md`)
          if (fs.existsSync(src)) {
            fs.copyFileSync(src, dest)
            p.log.success(`已新增 ${name}`)
            changed = true
          }
        }
      }
    }
  }

  if (category === 'rules') {
    const action = await p.select({
      message: 'Rules 操作',
      options: [
        { value: 'toggle', label: '🔄 啟用 / 停用' },
        { value: 'delete', label: '🗑️ 刪除' },
        { value: 'add', label: '➕ 從 ECC 新增' },
        { value: 'back', label: '← 返回' },
      ],
    })
    if (p.isCancel(action) || action === 'back')
      return false

    const rulesDir = path.join(CLAUDE_DIR, 'rules')
    if (action === 'toggle') {
      const selected = await p.multiselect({
        message: '切換啟用/停用狀態',
        options: data.rules.map(r => ({
          value: r.name,
          label: `${r.enabled ? pc.green('✔') : pc.red('✘')} ${r.name}`,
          hint: r.enabled ? '啟用中 → 將停用' : '已停用 → 將啟用',
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        for (const name of selected) {
          const rule = data.rules.find(r => r.name === name)
          if (rule.enabled) {
            fs.renameSync(
              path.join(rulesDir, `${name}.md`),
              path.join(rulesDir, `${name}.md.disabled`),
            )
            p.log.info(`已停用 ${name}`)
            changed = true
          }
          else {
            fs.renameSync(
              path.join(rulesDir, `${name}.md.disabled`),
              path.join(rulesDir, `${name}.md`),
            )
            p.log.success(`已啟用 ${name}`)
            changed = true
          }
        }
      }
    }
    else if (action === 'delete') {
      const selected = await p.multiselect({
        message: '選擇要刪除的 rules',
        options: data.rules.map(r => ({
          value: r.name,
          label: r.name,
          hint: r.source,
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        for (const name of selected) {
          for (const ext of ['.md', '.md.disabled']) {
            const fp = path.join(rulesDir, `${name}${ext}`)
            if (fs.existsSync(fp)) {
              fs.unlinkSync(fp)
              p.log.success(`已刪除 ${name}`)
              changed = true
            }
          }
        }
      }
    }
    else if (action === 'add') {
      const notInstalled = data.aiRes.rules.filter(
        name => !data.rules.some(r => r.name === name),
      )
      if (isEmpty(notInstalled)) {
        p.log.info('所有 ECC rules 已安裝')
        return false
      }
      const selected = await p.multiselect({
        message: '選擇要新增的 rules',
        options: notInstalled.map(name => ({ value: name, label: name })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        const aiResRulesDir = path.join(ECC_DIR, 'rules')
        for (const name of selected) {
          const src = path.join(aiResRulesDir, `${name}.md`)
          const dest = path.join(rulesDir, `${name}.md`)
          if (fs.existsSync(src)) {
            fs.copyFileSync(src, dest)
            p.log.success(`已新增 ${name}`)
            changed = true
          }
        }
      }
    }
  }

  if (category === 'skills') {
    const skills = data.skills ?? scanSkillsDir()
    const skillsDir = path.join(CLAUDE_DIR, 'skills')

    if (isEmpty(skills)) {
      p.log.info('尚未安裝任何 skill（~/.claude/skills/ 為空）')
      return false
    }

    const action = await p.select({
      message: 'Skills 操作',
      options: [
        { value: 'toggle', label: '🔄 啟用 / 停用' },
        { value: 'delete', label: '🗑️ 刪除' },
        { value: 'back', label: '← 返回' },
      ],
    })
    if (p.isCancel(action) || action === 'back')
      return false

    if (action === 'toggle') {
      const selected = await p.multiselect({
        message: '切換啟用/停用狀態',
        options: skills.map(s => ({
          value: s.name,
          label: `${s.enabled ? pc.green('✔') : pc.red('✘')} ${s.name}`,
          hint: s.enabled
            ? `啟用中 → 將停用 (${s.source})`
            : `已停用 → 將啟用 (${s.source})`,
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        for (const name of selected) {
          const skill = skills.find(s => s.name === name)
          const skillDir = fs
            .readdirSync(skillsDir, { withFileTypes: true })
            .filter(e => e.isDirectory())
            .flatMap((e) => {
              const sub = path.join(skillsDir, e.name)
              if (e.name === name)
                return [sub]
              try {
                return fs
                  .readdirSync(sub, { withFileTypes: true })
                  .filter(se => se.isDirectory() && se.name === name)
                  .map(se => path.join(sub, se.name))
              }
              catch {
                return []
              }
            })[0]

          if (!skillDir)
            continue
          if (skill.enabled) {
            fs.renameSync(
              path.join(skillDir, 'SKILL.md'),
              path.join(skillDir, 'SKILL.md.disabled'),
            )
            p.log.info(`已停用 ${name}`)
          }
          else {
            fs.renameSync(
              path.join(skillDir, 'SKILL.md.disabled'),
              path.join(skillDir, 'SKILL.md'),
            )
            p.log.success(`已啟用 ${name}`)
          }
          changed = true
        }
      }
    }
    else if (action === 'delete') {
      const selected = await p.multiselect({
        message: '選擇要刪除的 skills',
        options: skills.map(s => ({
          value: s.name,
          label: `${s.enabled ? '' : pc.red('✘ ')}${s.name}`,
          hint: s.source,
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        const confirm = await p.confirm({
          message: `確認刪除 ${selected.length} 個 skill 目錄？`,
        })
        if (confirm) {
          for (const name of selected) {
            const skillDir = fs
              .readdirSync(skillsDir, { withFileTypes: true })
              .filter(e => e.isDirectory())
              .flatMap((e) => {
                const sub = path.join(skillsDir, e.name)
                if (e.name === name)
                  return [sub]
                try {
                  return fs
                    .readdirSync(sub, { withFileTypes: true })
                    .filter(se => se.isDirectory() && se.name === name)
                    .map(se => path.join(sub, se.name))
                }
                catch {
                  return []
                }
              })[0]

            if (skillDir && fs.existsSync(skillDir)) {
              fs.rmSync(skillDir, { recursive: true, force: true })
              p.log.success(`已刪除 ${name}`)
              changed = true
            }
          }
        }
      }
    }
  }

  if (category === 'hooks') {
    const settingsPath = path.join(CLAUDE_DIR, 'settings.json')
    let settings = {}
    try {
      settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'))
    }
    catch {
      /* settings.json 不存在則略過 */
    }
    const hooksMap = settings.hooks || {}
    const events = Object.keys(hooksMap)

    if (isEmpty(events)) {
      p.log.info('沒有已配置的 Hook 事件')
      return false
    }

    const selected = await p.multiselect({
      message:
        '選擇要移除的 Hook 事件（移除後可透過 pnpm run d:setup 重新安裝）',
      options: events.map(e => ({
        value: e,
        label: e,
        hint: `${(hooksMap[e] || []).reduce((s, m) => s + (m.hooks?.length || 0), 0)} 個子 hook`,
      })),
      required: false,
    })
    if (!p.isCancel(selected) && !isEmpty(selected)) {
      for (const event of selected) {
        delete settings.hooks[event]
        p.log.info(`已移除 ${event}`)
      }
      fs.writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`)
      p.log.success(
        `已移除 ${selected.length} 個 Hook 事件（pnpm run d:setup 可重新安裝）`,
      )
      return true
    }
  }

  if (category === 'zsh') {
    const zshSrc = path.join(REPO, 'zsh', '.zshrc.d', 'conf')
    const zshDest = path.join(HOME, '.zshrc.d', 'conf')
    const selected = await p.multiselect({
      message: '切換 ZSH 模組安裝狀態',
      options: data.zsh.available.map(m => ({
        value: m,
        label: `${data.zsh.installed.includes(m) ? pc.green('✔') : pc.red('✘')} ${m}`,
        hint: data.zsh.installed.includes(m)
          ? '已安裝 → 將卸載'
          : '未安裝 → 將安裝',
      })),
      required: false,
    })
    if (!p.isCancel(selected) && !isEmpty(selected)) {
      fs.mkdirSync(zshDest, { recursive: true })
      for (const m of selected) {
        const dest = path.join(zshDest, `${m}.zsh`)
        if (data.zsh.installed.includes(m)) {
          fs.unlinkSync(dest)
          p.log.info(`已卸載 ${m}`)
          changed = true
        }
        else {
          fs.copyFileSync(path.join(zshSrc, `${m}.zsh`), dest)
          p.log.success(`已安裝 ${m}`)
          changed = true
        }
      }
    }
  }

  if (category === 'permissions') {
    const action = await p.select({
      message: 'Permissions 操作',
      options: [
        { value: 'add', label: '➕ 新增 allow 規則' },
        { value: 'delete', label: '🗑️ 刪除 allow 規則' },
        { value: 'back', label: '← 返回' },
      ],
    })
    if (p.isCancel(action) || action === 'back')
      return false

    const settingsPath = path.join(CLAUDE_DIR, 'settings.json')
    let settings = {}
    try {
      settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'))
    }
    catch {
      /* settings.json 不存在則略過 */
    }
    if (!settings.permissions)
      settings.permissions = { allow: [], deny: [] }

    if (action === 'add') {
      const rule = await p.text({
        message: '輸入 permission 規則（如 Bash(docker *)）',
      })
      if (!p.isCancel(rule) && rule) {
        settings.permissions.allow.push(rule)
        fs.writeFileSync(
          settingsPath,
          `${JSON.stringify(settings, null, 2)}\n`,
        )
        p.log.success(`已新增: ${rule}`)
        changed = true
      }
    }
    else if (action === 'delete') {
      const selected = await p.multiselect({
        message: '選擇要刪除的規則',
        options: (settings.permissions.allow || []).map(r => ({
          value: r,
          label: r,
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        settings.permissions.allow = settings.permissions.allow.filter(
          r => !selected.includes(r),
        )
        fs.writeFileSync(
          settingsPath,
          `${JSON.stringify(settings, null, 2)}\n`,
        )
        p.log.success(`已刪除 ${selected.length} 條規則`)
        changed = true
      }
    }
  }

  if (category === 'claudemd') {
    const action = await p.select({
      message: 'CLAUDE.md 操作',
      options: [
        { value: 'delete', label: '🗑️ 刪除指定項目的 CLAUDE.md' },
        { value: 'back', label: '← 返回' },
      ],
    })
    if (p.isCancel(action) || action === 'back')
      return false

    if (action === 'delete') {
      const selected = await p.multiselect({
        message: '選擇要刪除的 CLAUDE.md',
        options: data.claudeMd.map(proj => ({
          value: proj.path,
          label: proj.path,
          hint: proj.mtime.slice(0, 10),
        })),
        required: false,
      })
      if (!p.isCancel(selected) && !isEmpty(selected)) {
        for (const projPath of selected) {
          const realPath = projPath.replace('~', HOME)
          const mdPath = path.join(realPath, 'CLAUDE.md')
          if (fs.existsSync(mdPath)) {
            fs.unlinkSync(mdPath)
            p.log.success(`已刪除 ${projPath}/CLAUDE.md`)
            changed = true
          }
        }
      }
    }
  }

  return changed
}

