/**
 * 掃描 ~/.claude/skills/ 目錄，返回所有 skill 項目。
 * 支援 2 層結構（skills/{name}/SKILL.md）與 3 層結構（skills/{source}/{name}/SKILL.md）。
 * @returns {{ name: string, source: string, enabled: boolean }[]}
 */
function scanSkillsDir() {
  const skillsDir = path.join(CLAUDE_DIR, 'skills')
  if (!fs.existsSync(skillsDir))
    return []

  const skills = []

  /**
   * 從 SKILL.md 內容解析 ab-tao marker 的來源標識
   * @param {string} filePath
   * @returns {string|null} source 字串，或 null 表示無 marker
   */
  function parseSource(filePath) {
    try {
      const content = fs.readFileSync(filePath, 'utf8')
      // 匹配 <!-- generated by ab-tao::SOURCE --> 或 <!-- generated by ab-tao -->
      const match = content.match(
        /<!--\s*generated by ab-tao(?:::([^\s>]+))?\s*-->/,
      )
      if (!match)
        return null
      return match[1] || 'ab-tao' // 有 ::SOURCE 則取之，否則回傳 'ab-tao'
    }
    catch {
      return null
    }
  }

  /**
   * 遞迴走訪目錄，找出含有 SKILL.md 的葉子目錄
   * @param {string} dir 當前目錄
   * @param {number} depth 當前深度（從 skillsDir 算起，max 3）
   * @param {string|null} parentName 上層目錄名（用於 3 層結構的 source）
   */
  function walk(dir, depth, parentName) {
    if (depth > 3)
      return

    let entries
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true })
    }
    catch {
      return
    }

    // 優先判斷當前目錄是否為 skill 葉子（含有 SKILL.md 或 SKILL.md.disabled）
    const skillFile = entries.find(
      e =>
        e.isFile() && (e.name === 'SKILL.md' || e.name === 'SKILL.md.disabled'),
    )
    if (skillFile) {
      const enabled = skillFile.name === 'SKILL.md'
      const filePath = path.join(dir, skillFile.name)
      const markerSource = parseSource(filePath)
      const dirName = path.basename(dir)

      let source
      if (markerSource && markerSource !== 'ab-tao') {
        // marker 帶有明確 SOURCE（如 <!-- generated by ab-tao::ecc -->）
        source = markerSource
      }
      else if (markerSource === 'ab-tao' && parentName) {
        // 3 層結構：有 marker 但無 SOURCE → 使用上層目錄名作為 source
        source = parentName
      }
      else if (markerSource === 'ab-tao') {
        // 2 層結構：有 marker，無上層可用
        source = 'ab-tao'
      }
      else {
        // 無 marker → 用戶自訂
        source = 'custom'
      }

      skills.push({ name: dirName, source, enabled })
      return // 已是葉子，不再深入
    }

    // 非葉子，繼續遞迴子目錄
    for (const entry of entries) {
      if (entry.isDirectory()) {
        walk(path.join(dir, entry.name), depth + 1, path.basename(dir))
      }
    }
  }

  // 從 depth=1 開始（skillsDir 本身為 depth=0）
  let topEntries
  try {
    topEntries = fs.readdirSync(skillsDir, { withFileTypes: true })
  }
  catch {
    return []
  }
  for (const entry of topEntries) {
    if (entry.isDirectory()) {
      walk(path.join(skillsDir, entry.name), 1, null)
    }
  }

  return skills
}

async function main() {
  p.intro(pc.bold('ab-tao 配置管理中心'))
  const spinner = p.spinner()
  spinner.start('掃描使用數據（首次可能需要 10-30 秒）…')
  let data
  try {
    data = await collectFullStatus()
  }
  finally {
    spinner.stop('掃描完成')
  }

  await terminalMode(data)
}

