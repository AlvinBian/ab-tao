/**
 * CLAUDE.md 生成 — 全部角色使用 AI 生成，靜態模板作為 fallback
 *
 * 八大模塊結構：
 * 1. 核心工作流程（RESEARCH → PLAN → IMPLEMENT）
 * 2. 質量紅線（絕不清單）
 * 3. 構建與測試（動態生成）
 * 4. 編碼標準（融入 CODING_STYLE_CONTENT）
 * 5. 架構摘要（AI 分析生成）
 * 6. 測試規範（融入 TESTING_CONTENT）
 * 7. Git 規範（融入 GIT_WORKFLOW_CONTENT）
 * 8. 壓縮指令（保留改動檔案、測試、未完成任務）
 */

import * as p from "@clack/prompts";
import { AI_ECC_MODEL, AI_ECC_TIMEOUT } from "../core/constants.mjs";
import { callClaudeJSON } from "../external/claude-cli.mjs";

/**
 * 生成 CLAUDE.md 內容
 *
 * 所有角色都嘗試 AI 生成，失敗回退到靜態模板。
 * main: 完整版（技術棧 + 架構 + 規範 + 指令）
 * temp: 精簡版（摘要 + 快速上手）
 * tool: 最小版（一句描述）
 */
export async function generateClaudeMd({
	repoName,
	role,
	reasoning,
	stacks,
	meta,
}) {
	try {
		return await generateWithAI(repoName, role, reasoning, stacks, meta);
	} catch (error) {
		// AI 失敗，記錄診斷資訊後使用靜態模板
		const errorMsg = error?.message || String(error);
		const isTokenLimit =
			errorMsg.includes("token") || errorMsg.includes("context");
		p.log.warn(
			`⚠️ CLAUDE.md AI 生成失敗 （${repoName} · ${role}）\n` +
				`   原因：${errorMsg.slice(0, 100)}\n` +
				`   Token 超限：${isTokenLimit ? "是" : "否"}\n` +
				`   Fallback：靜態模板 (${role})`,
		);

		if (role === "tool") return fallbackTool(repoName, meta);
		if (role === "temp") return fallbackTemp(repoName, reasoning, stacks, meta);
		return fallbackMain(repoName, reasoning, stacks, meta);
	}
}

// ── AI 生成（統一入口）──

async function generateWithAI(repoName, role, reasoning, stacks, meta) {
	const stackText = stacks
		? Object.entries(stacks)
				.map(([cat, items]) => `${cat}: ${items.join(", ")}`)
				.join("\n")
		: "";

	const timestamp = new Date().toISOString().split("T")[0];
	const stackList = stackText ? stackText.replace(/\n/g, " · ") : "";

	const rolePrompts = {
		main: `為 "${repoName}" 生成完整的 CLAUDE.md（Claude Code 專案上下文）。

專案摘要：${reasoning || meta?.description || ""}
技術棧：
${stackText}

使用以下八大模塊結構生成 Markdown（繁體中文，<200 行）：

## 模塊 1: 核心工作流程
列出每個任務的三階段：RESEARCH → PLAN → IMPLEMENT
1. 研究：檢查現有代碼，搜索相關實現
2. 計劃：列出文件清單 + 方案 + 風險，獲確認後才編碼
3. 實現：遵循風格 + 完整錯誤處理 + 同步寫測試

## 模塊 2: 質量紅線
列出 4-5 點絕不做什麼：
- 絕不提交未通過測試的代碼
- 絕不使用 TODO/FIXME 作為最終代碼
- 絕不跳過錯誤處理或吞掉異常
- 絕不硬編碼密鑰或敏感資訊
- 絕不使用 @ts-ignore 或 eslint-disable

## 模塊 3: 構建與測試
根據技術棧列出主要指令（build、test、lint、dev）

## 模塊 4: 編碼標準
簡要說明編碼風格原則（不可變性、模組化、錯誤處理）

## 模塊 5: 架構摘要
AI 分析並描述專案核心架構（3-5 點）

## 模塊 6: 測試規範
說明測試框架、覆蓋率目標、測試組織方式

## 模塊 7: Git 規範
Commit 格式 + PR 工作流程摘要

## 模塊 8: 壓縮指令
列出壓縮時保留的內容：改動檔案列表、測試命令和結果、未完成任務`,

		temp: `為 "${repoName}" 生成精簡的 CLAUDE.md（Claude Code 專案上下文）。

專案摘要：${reasoning || meta?.description || ""}
技術棧：${stackText || "未知"}

生成以下 Markdown（繁體中文，15 行以內）：
# ${repoName}
${reasoning || meta?.description || ""}

## 快速上手
列出主要開發指令

## 技術棧
${stackText || "見 package.json"}

## 注意事項
列出 2-3 項關鍵事項`,

		tool: `為 "${repoName}" 生成最小的 CLAUDE.md（一句描述 + 快速參考）。

專案摘要：${reasoning || meta?.description || ""}

生成 Markdown（繁體中文，5 行以內）：
# ${repoName}
${reasoning || meta?.description || ""}

## 快速參考
主要開發指令或使用方式`,
	};

	const result = await callClaudeJSON(rolePrompts[role] || rolePrompts.temp, {
		model: AI_ECC_MODEL,
		effort: "low",
		timeoutMs: AI_ECC_TIMEOUT,
		retries: 0,
	});

	const content = typeof result === "string" ? result : result?.result;
	if (!content) throw new Error("AI generation failed");

	// 檢查長度，如果超過 200 行則截斷並加警告
	const lineCount = content.split("\n").length;
	if (lineCount > 200) {
		const truncated = content.split("\n").slice(0, 200).join("\n");
		return `${truncated}\n\n<!-- 警告: 生成內容已從 ${lineCount} 行截斷至 200 行 -->`;
	}

	// 新增簽名註釋（不消耗 token）
	const metaStackList =
		Object.entries(meta?.stacks || {})
			.flatMap(([, items]) => items)
			.join(", ") ||
		stackList ||
		"未知";
	const signature = `\n\n<!-- Generated by ab-tao · ${timestamp} · ${metaStackList} -->`;

	return content + signature;
}

// ── 靜態 Fallback ──

function fallbackTool(repoName, meta) {
	const timestamp = new Date().toISOString().split("T")[0];
	return `# ${repoName}

${meta?.description || repoName}

## 快速參考
使用方式見 README。

<!-- Generated by ab-tao · ${timestamp} · tool -->`;
}

function fallbackTemp(repoName, reasoning, stacks, meta) {
	const techList = stacks
		? Object.entries(stacks)
				.flatMap(([, items]) => items)
				.join(" · ")
		: "";
	const timestamp = new Date().toISOString().split("T")[0];
	const stackDesc = techList || "見 package.json";
	return `# ${repoName}

${reasoning || meta?.description || repoName}

## 快速上手

\`\`\`bash
pnpm install
pnpm run dev
pnpm run test
\`\`\`

## 技術棧

${stackDesc}

## 注意事項

- 遵循 Conventional Commits 格式
- 執行測試後才提交
- 查看 README 了解詳細指令

<!-- Generated by ab-tao · ${timestamp} · ${techList || "temp"} -->`;
}

function fallbackMain(repoName, reasoning, stacks, meta) {
	const stackSections = stacks
		? Object.entries(stacks)
				.map(([cat, items]) => `- **${cat}**：${items.join(", ")}`)
				.join("\n")
		: "";
	const timestamp = new Date().toISOString().split("T")[0];
	const stackList = stacks
		? Object.entries(stacks)
				.flatMap(([, items]) => items)
				.join(", ")
		: "";

	return `# ${repoName}

${reasoning || meta?.description || repoName}

## 核心工作流程

每個任務遵循三階段：
1. **研究** — 檢查現有代碼，搜索相關實現
2. **計劃** — 列出文件清單、方案、風險，獲確認後編碼
3. **實現** — 遵循風格、完整錯誤處理、同步寫測試

## 質量紅線

- 絕不提交未通過測試的代碼
- 絕不使用 TODO/FIXME 作為最終代碼
- 絕不跳過錯誤處理或吞掉異常
- 絕不硬編碼密鑰或敏感資訊

## 構建與測試

\`\`\`bash
pnpm install    # 安裝依賴
pnpm run dev    # 開發模式
pnpm run build  # 構建
pnpm run test   # 執行測試
pnpm run lint   # 程式碼檢查
\`\`\`

## 編碼標準

- 優先不可變性，避免 in-place 修改
- 公開 API 必須有明確的存取修飾符
- async/await 而非阻塞呼叫
- 丟出具體異常並記錄結構化屬性

## 架構摘要

${stackSections || "見 package.json"}

## 測試規範

- 鏡像 src/ 結構到 tests/
- 清楚分離單元、整合、端對端測試
- 目標 80%+ 行覆蓋率
- 重點涵蓋：領域邏輯、驗證、授權、失敗路徑

## Git 規範

**Commit 格式：**
\`\`\`
<type>: <description>

<optional body>
\`\`\`

類型：feat、fix、refactor、docs、test、chore、perf、ci

**PR 工作流程：**
1. 分析完整 commit 歷史
2. 使用 \`git diff [base-branch]...HEAD\` 檢視所有變更
3. 撰寫全面的 PR 摘要
4. 包含測試計畫

## 壓縮指令

當上下文飽和時，保留：
- 改動檔案列表（\`git status\`）
- 測試命令和結果
- 未完成的任務清單
- 當前進度與後續步驟

<!-- Generated by ab-tao · ${timestamp} · ${stackList || "main"} -->`;
}
